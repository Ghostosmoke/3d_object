# =============================================================================
# ГЛАВНАЯ ФУНКЦИЯ UPDATE (ИГРОВОЙ ЦИКЛ)
# =============================================================================
def update():
    """
    Эта функция вызывается автоматически каждый кадр (обычно 60 раз в секунду).
    Здесь происходит вся анимация, движение и логика игры.
    """
    # Объявляем глобальные переменные, которые будем изменять в этой функции
    global time_tracker, is_colliding

    # -------------------------------------------------------------------------
    # ВЫЧИСЛЕНИЕ СКОРОСТИ ДВИЖЕНИЯ
    # -------------------------------------------------------------------------
    # time.dt - время, прошедшее с последнего кадра (в секундах)
    # Умножение на dt делает движение независимым от FPS (кадров в секунду)
    # Это гарантирует одинаковую скорость на разных компьютерах
    speed = 4 * time.dt

    # -------------------------------------------------------------------------
    # ДВИЖЕНИЕ ВПЕРЁД ПО ОСИ X
    # -------------------------------------------------------------------------
    knot.x += speed  # Увеличиваем X-координату (движение слева направо)
    time_tracker += speed  # Увеличиваем счётчик времени для синусоиды

    # -------------------------------------------------------------------------
    # ДВИЖЕНИЕ ПО СИНУСОИДЕ (ВВЕРХ-ВНИЗ ПО ОСИ Y)
    # -------------------------------------------------------------------------
    # np.sin() возвращает значение от -1 до 1
    # Умножаем на 3 для амплитуды (размах колебаний = 6 единиц: от -3 до +3)
    # time_tracker * 0.5 - частота колебаний (чем больше, тем чаще)
    knot.y = np.sin(time_tracker * 0.5) * 3

    # -------------------------------------------------------------------------
    # ДВИЖЕНИЕ ПО КОСИНУСОИДЕ (ВГЛУБЬ-НАРУЖУ ПО ОСИ Z)
    # -------------------------------------------------------------------------
    # Добавляет движение по оси Z для усиления 3D эффекта
    # Косинус сдвинут относительно синуса на 90 градусов (фазовый сдвиг)
    # Умножаем на 2 для амплитуды (размах = 4 единицы: от -2 до +2)
    knot.z = np.cos(time_tracker * 0.5) * 2

    # -------------------------------------------------------------------------
    # ВРАЩЕНИЕ ФИГУРЫ ВОКРУГ СОБСТВЕННЫХ ОСЕЙ
    # -------------------------------------------------------------------------
    # rotation_y - вращение вокруг вертикальной оси (как волчок)
    # rotation_z - вращение вокруг оси Z (наклон вбок)
    # 50 * time.dt - скорость вращения (50 градусов в секунду)
    knot.rotation_y += 50 * time.dt  # Вращение вокруг Y
    knot.rotation_z += 20 * time.dt  # Вращение вокруг Z

    # -------------------------------------------------------------------------
    # ЦИКЛИЧЕСКОЕ ДВИЖЕНИЕ (ТЕЛЕПОРТ НАЧАЛО)
    # -------------------------------------------------------------------------
    # Если узел улетел за правую границу сцены (X > 10)
    if knot.x > 10:
        knot.x = -10  # Возвращаем на левую границу (X = -10)
        time_tracker = 0  # Сбрасываем счётчик времени (начало новой синусоиды)

    # =============================================================================
    # ПРОВЕРКА СТОЛКНОВЕНИЙ (COLLISION DETECTION)
    # =============================================================================

    # -------------------------------------------------------------------------
    # ЗАПРОС НА ПЕРЕСЕЧЕНИЕ ОБЪЕКТОВ
    # -------------------------------------------------------------------------
    # intersects() пускает луч из центра объекта и проверяет пересечения
    # Возвращает объект hit_info с информацией о попадании
    hit_info = knot.intersects()

    # -------------------------------------------------------------------------
    # ОБРАБОТКА РЕЗУЛЬТАТА ПРОВЕРКИ
    # -------------------------------------------------------------------------
    # hit_info.hit - True если было попадание в какой-либо объект
    # hit_info.entity - ссылка на объект, в который попали
    if hit_info.hit and hit_info.entity == barrier:
        # Произошло столкновение с барьером

        # Проверяем флаг, чтобы не выполнять код каждый кадр столкновения
        # Это предотвращает мерцание цвета и лишние вычисления
        if not is_colliding:
            # Только что началось столкновение (первый кадр пересечения)

            # Меняем цвет узла на красный
            knot.color = color_knot_hit

            # Меняем цвет барьера на лайм (зелёный)
            barrier.color = color_barrier_hit

            # Устанавливаем флаг, что сейчас идёт столкновение
            is_colliding = True

            # Обновляем текст статуса на экране
            status_text.text = 'Статус: СТОЛКНОВЕНИЕ!'
            status_text.color = color.red  # Красный цвет текста

            # Вывод в консоль для отладки
            print("Collision detected!")
    else:
        # Столкновения нет (или попали в другой объект, не барьер)

        # Проверяем флаг, чтобы не выполнять код каждый кадр без столкновения
        if is_colliding:
            # Только что закончилось столкновение

            # Возвращаем оригинальный цвет узла (голубой)
            knot.color = color_knot_normal

            # Возвращаем оригинальный цвет барьера (оранжевый)
            barrier.color = color_barrier_normal

            # Сбрасываем флаг столкновения
            is_colliding = False

            # Возвращаем текст статуса в исходное состояние
            status_text.text = 'Статус: Ожидание'
            status_text.color = color.white  # Белый цвет текста


# =============================================================================
# ЗАПУСК ПРИЛОЖЕНИЯ
