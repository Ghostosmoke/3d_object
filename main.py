# 1. ГЕНЕРАЦИЯ ФИГУРЫ (ПРОЦЕДУРНЫЙ ТОР-УЗЕЛ)
# ============================================================================
def generate_torus_knot_mesh(tube_radius=0.3 , radial_segments=12 , tubular_segments=64):
    """
    Генерирует 3D-меш (сетку) для Тор-узла используя математические формулы.

    Параметры:
    - tube_radius: радиус трубки самого узла (толщина)
    - radial_segments: количество сегментов вокруг трубки (чем больше, тем круглее сечение)
    - tubular_segments: количество сегментов вдоль основной кривой узла (чем больше, тем плавнее изгибы)

    Возвращает:
    - vertices: список координат всех вершин меша
    - triangles: список индексов вершин, образующих треугольники
    """
    vertices = []  # Список для хранения координат вершин (x, y, z)
    triangles = []  # Список для хранения индексов вершин, образующих треугольники

    # ------------------------------------------------------------------------
    # МАТЕМАТИЧЕСКАЯ ФОРМУЛА ТОР-УЗЛА
    # ------------------------------------------------------------------------
    def knot_func(t):
        """
        Параметрическое уравнение Тор-узла типа (2,3).
        t - параметр от 0 до 2π (один полный оборот по основной кривой)

        Формула создаёт замкнутую кривую, которая закручивается вокруг тора
        2 раза по большому кругу и 3 раза по малому кругу.
        """
        # x-координата: основное вращение вокруг оси Z + модуляция радиуса
        x = (2 + np.cos(3 * t)) * np.cos(2 * t)
        # y-координата: основное вращение вокруг оси Z + модуляция радиуса
        y = (2 + np.cos(3 * t)) * np.sin(2 * t)
        # z-координата: вертикальные колебания (высота узла)
        z = np.sin(3 * t)
        return np.array([x , y , z])

    # ------------------------------------------------------------------------
    # ГЕНЕРАЦИЯ ТОЧЕК ВДОЛЬ ОСНОВНОЙ КРИВОЙ
    # ------------------------------------------------------------------------
    # Создаём массив параметров t от 0 до 2π (полный круг)
    # endpoint=False - не включаем последнюю точку (она совпадает с первой)
    ts = np.linspace(0 , 2 * np.pi , tubular_segments , endpoint=False)

    # Вычисляем координаты точек вдоль основной кривой узла
    points = np.array([knot_func(t) for t in ts])

    # ------------------------------------------------------------------------
    # СОЗДАНИЕ ТРУБКИ ВОКРУГ КРИВОЙ
    # ------------------------------------------------------------------------
    # Для каждой точки на основной кривой создаём кольцо вершин вокруг неё
    # Это превращает линию в объёмную трубку
    for i , center in enumerate(points):
        # Находим следующую точку для вычисления направления (касательной)
        next_center = points[(i + 1) % len(points)]  # % len - зацикливание на первую точку

        # Вычисляем вектор касательной (направление кривой в этой точке)
        tangent = next_center - center
        tangent = tangent / np.linalg.norm(tangent)  # Нормализуем (делаем длину = 1)

        # --------------------------------------------------------------------
        # ВЫЧИСЛЕНИЕ ЛОКАЛЬНОЙ СИСТЕМЫ КООРДИНАТ
        # --------------------------------------------------------------------
        # Нужно создать две перпендикулярные оси для построения кольца вокруг кривой
        # Это нужно чтобы трубка не перекручивалась

        # Вектор "вверх" по умолчанию (мировая ось Z)
        up = np.array([0 , 0 , 1])

        # Если касательная почти параллельна оси Z, меняем "вверх" на ось Y
        # Это предотвращает проблемы с вычислением перпендикуляров
        if abs(np.dot(tangent , up)) > 0.9:
            up = np.array([0 , 1 , 0])

        # Нормаль - вектор перпендикулярный касательной и "вверх"
        normal = np.cross(tangent , up)
        normal = normal / np.linalg.norm(normal)  # Нормализуем

        # Бинормаль - третий перпендикулярный вектор (дополняет систему координат)
        binormal = np.cross(tangent , normal)

        # --------------------------------------------------------------------
        # ГЕНЕРАЦИЯ ВЕРШИН КОЛЬЦА
        # --------------------------------------------------------------------
        # Создаём radial_segments вершин по кругу вокруг центральной точки
        for j in range(radial_segments):
            # Угол для текущей вершины кольца (0 до 2π)
            angle = 2 * np.pi * j / radial_segments

            # Вычисляем смещение от центра трубки
            # cos(angle)*normal + sin(angle)*binormal создаёт круг в плоскости кольца
            # Умножаем на tube_radius для получения нужной толщины
            offset = (np.cos(angle) * normal + np.sin(angle) * binormal) * tube_radius

            # Финальная координата вершины = центр кривой + смещение
            vertex = center + offset
            vertices.append(vertex)

    # ------------------------------------------------------------------------
    # СОЗДАНИЕ ТРЕУГОЛЬНИКОВ (СОЕДИНЕНИЕ ВЕРШИН)
    # ------------------------------------------------------------------------
    # Соединяем вершины в треугольники для создания поверхности
    # Каждый квадрат между 4 вершинами разбивается на 2 треугольника
    for i in range(tubular_segments):
        for j in range(radial_segments):
            # Индексы текущей вершины и трёх соседних
            current = i * radial_segments + j
            next_i = ((i + 1) % tubular_segments) * radial_segments + j
            next_j = i * radial_segments + ((j + 1) % radial_segments)
            next_ij = ((i + 1) % tubular_segments) * radial_segments + ((j + 1) % radial_segments)

            # Создаём два треугольника для каждого квада
            # Порядок вершин важен для правильных нормалей (направления граней)
            triangles.append([current , next_ij , next_i])
            triangles.append([current , next_j , next_ij])

    return vertices , triangles


