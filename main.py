# ФУНКЦИЯ ГЕНЕРАЦИИ МЕША ТОР-УЗЛА (TORUS KNOT)
# =============================================================================
def generate_torus_knot_mesh(tube_radius=0.3, radial_segments=12, tubular_segments=64):
    """
    Создаёт трёхмерную сетку (меш) для тор-узла типа (2,3).

    Параметры:
    - tube_radius: радиус трубки (толщина самого узла)
    - radial_segments: количество точек по окружности сечения трубки (чем больше, тем круглее)
    - tubular_segments: количество точек вдоль основной кривой узла (чем больше, тем плавнее)

    Возвращает:
    - vertices: список координат всех вершин (точек) меша
    - triangles: список индексов вершин, которые соединяются в треугольники
    """

    vertices = []  # Пустой список для хранения координат вершин (x, y, z)
    triangles = []  # Пустой список для хранения индексов треугольников

    # -------------------------------------------------------------------------
    # ПАРАМЕТРИЧЕСКАЯ ФОРМУЛА ТОР-УЗЛА
    # -------------------------------------------------------------------------
    def knot_func(t):
        """
        Математическая формула тор-узла (2,3).
        Параметр t изменяется от 0 до 2π (один полный оборот).

        Числа 2 и 3 означают:
        - 2 оборота вокруг большой оси тора
        - 3 оборота вокруг малой оси тора
        """
        # Вычисляем координаты X, Y, Z по параметрическим уравнениям
        x = (2 + np.cos(3 * t)) * np.cos(2 * t)  # Координата по оси X
        y = (2 + np.cos(3 * t)) * np.sin(2 * t)  # Координата по оси Y
        z = np.sin(3 * t)  # Координата по оси Z (высота)

        return np.array([x, y, z])  # Возвращаем массив из трёх координат

    # -------------------------------------------------------------------------
    # ГЕНЕРАЦИЯ ТОЧЕК ВДОЛЬ ОСНОВНОЙ КРИВОЙ УЗЛА
    # -------------------------------------------------------------------------
    # Создаём массив значений t от 0 до 2π (полный круг)
    # endpoint=False означает, что последняя точка не включается (она равна первой)
    ts = np.linspace(0, 2 * np.pi, tubular_segments, endpoint=False)

    # Вычисляем координаты точек вдоль кривой для каждого значения t
    points = np.array([knot_func(t) for t in ts])

    # -------------------------------------------------------------------------
    # СОЗДАНИЕ ТРУБКИ ВОКРУГ КРИВОЙ (ОБЪЁМНАЯ ФИГУРА)
    # -------------------------------------------------------------------------
    # Для каждой точки на основной кривой создаём кольцо вершин вокруг неё
    # Это превращает одномерную линию в трёхмерную трубку
    for i, center in enumerate(points):
        # Находим следующую точку на кривой для вычисления направления
        # % len(points) обеспечивает зацикливание (последняя точка -> первая)
        next_center = points[(i + 1) % len(points)]

        # Вычисляем вектор касательной (направление кривой в данной точке)
        tangent = next_center - center

        # Нормализуем касательную (делаем её длину равной 1)
        # Это нужно для корректных вычислений перпендикулярных векторов
        tangent = tangent / np.linalg.norm(tangent)

        # -------------------------------------------------------------------------
        # ВЫЧИСЛЕНИЕ ЛОКАЛЬНОЙ СИСТЕМЫ КООРДИНАТ (FRENET FRAME)
        # -------------------------------------------------------------------------
        # Нужно создать два перпендикулярных вектора для построения кольца
        # Это гарантирует, что трубка не будет перекручиваться

        # Базовый вектор "вверх" (мировая ось Z)
        up = np.array([0, 0, 1])

        # Если касательная почти параллельна оси Z, меняем "вверх" на ось Y
        # Это предотвращает математическую ошибку (деление на ноль при cross product)
        if abs(np.dot(tangent, up)) > 0.9:
            up = np.array([0, 1, 0])

        # Вектор нормали - перпендикулярен касательной и вектору "вверх"
        normal = np.cross(tangent, up)
        normal = normal / np.linalg.norm(normal)  # Нормализуем

        # Вектор бинормали - третий перпендикулярный вектор
        # Вместе tangent, normal, binormal образуют систему координат
        binormal = np.cross(tangent, normal)

        # -------------------------------------------------------------------------
        # ГЕНЕРАЦИЯ ВЕРШИН КОЛЬЦА ВОКРУГ ТОЧКИ КРИВОЙ
        # -------------------------------------------------------------------------
        # Создаём radial_segments вершин по кругу вокруг центральной точки
        for j in range(radial_segments):
            # Вычисляем угол для текущей вершины кольца (от 0 до 2π)
            angle = 2 * np.pi * j / radial_segments

            # Вычисляем смещение от центра трубки
            # cos(angle)*normal + sin(angle)*binormal создаёт круг в плоскости кольца
            # Умножаем на tube_radius для получения нужной толщины трубки
            offset = (np.cos(angle) * normal + np.sin(angle) * binormal) * tube_radius

            # Финальная координата вершины = центр кривой + смещение
            vertex = center + offset

            # Добавляем вершину в список (преобразуем numpy.array в список)
            vertices.append(list(vertex))

    # -------------------------------------------------------------------------
    # СОЗДАНИЕ ТРЕУГОЛЬНИКОВ (СОЕДИНЕНИЕ ВЕРШИН В ПОВЕРХНОСТЬ)
    # -------------------------------------------------------------------------
    # Соединяем вершины в треугольники для создания сплошной поверхности
    # Каждый квадрат между 4 соседними вершинами разбивается на 2 треугольника

    for i in range(tubular_segments):  # Проходим по всем сегментам вдоль кривой
        for j in range(radial_segments):  # Проходим по всем вершинам кольца

            # Вычисляем индексы четырёх вершин, образующих квадрат
            current = i * radial_segments + j  # Текущая вершина
            next_i = ((i + 1) % tubular_segments) * radial_segments + j  # Следующая вдоль кривой
            next_j = i * radial_segments + ((j + 1) % radial_segments)  # Следующая по кольцу
            next_ij = ((i + 1) % tubular_segments) * radial_segments + ((j + 1) % radial_segments)  # Диагональная

            # Создаём два треугольника для каждого квадрата
            # Порядок вершин важен для правильных нормалей (направление граней)
            triangles.append([current, next_ij, next_i])  # Первый треугольник
            triangles.append([current, next_j, next_ij])  # Второй треугольник

    # Возвращаем сгенерированные вершины и треугольники
    return vertices, triangles


